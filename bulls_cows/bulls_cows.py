def feedback_code(secret, guess):
    mask = common = bulls = 0
    for i in range(4):
        if secret[i] == guess[i]:
            mask |= 1 << i
            bulls += 1
        if guess[i] in secret:
            common += 1
    return mask * 8 + (common - bulls)


